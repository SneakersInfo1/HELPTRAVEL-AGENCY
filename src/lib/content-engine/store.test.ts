import assert from "node:assert/strict";
import { mkdtemp, readFile, readdir, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";

import { ContentStore, ContentStoreError, NODE_FS, type FsLike } from "./store";
import { makeDocument } from "./test-helpers";

function delegatedFs(overrides: Partial<FsLike>): FsLike {
  return { ...NODE_FS, ...overrides };
}

test("indeks zawiera posortowane statyczne importy w wymaganym kształcie", async (t) => {
  const root = await mkdtemp(path.join(os.tmpdir(), "seo-store-index-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const store = new ContentStore(root);
  await store.writeDocumentsAtomically([
    makeDocument({ id: "zeta", canonicalUrl: "/porownanie/zeta", contentType: "comparison_enrichment" }),
    makeDocument({ id: "alfa", canonicalUrl: "/inspiracje/alfa", contentType: "article" }),
  ]);
  await store.regenerateIndex();
  const index = await readFile(path.join(root, "index.generated.ts"), "utf8");
  assert.equal(
    index,
    `// AUTO-GENERATED by scripts/content-engine/run.ts — nie edytuj ręcznie.
import doc0 from "./articles/alfa.json";
import doc1 from "./comparisons/zeta.json";
export const CONTENT_DOCUMENTS: unknown[] = [doc0, doc1];
`,
  );
});

test("EACCES podczas zapisu nie zostawia częściowego dokumentu", async (t) => {
  const root = await mkdtemp(path.join(os.tmpdir(), "seo-store-eacces-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const failing = delegatedFs({
    writeFile: async (target, data, options) => {
      if (target.endsWith(".tmp")) throw Object.assign(new Error("permission denied"), { code: "EACCES" });
      await NODE_FS.writeFile(target, data, options);
    },
  });
  const store = new ContentStore(root, failing);
  await assert.rejects(store.writeDocumentsAtomically([makeDocument()]), ContentStoreError);
  const names = await readdir(path.join(root, "articles"));
  assert.deepEqual(names, []);
});

test("awaria po pierwszym pliku przywraca sklep bajt w bajt", async (t) => {
  const root = await mkdtemp(path.join(os.tmpdir(), "seo-store-rollback-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const first = makeDocument({ id: "alfa", canonicalUrl: "/inspiracje/alfa", title: "Miejski ogród Alfa na spokojny spacer" });
  const second = makeDocument({ id: "beta", canonicalUrl: "/inspiracje/beta", title: "Miejski ogród Beta na spokojny spacer" });
  const initial = new ContentStore(root);
  await initial.writeDocumentsAtomically([first, second]);
  initial.commitLastWrite();
  const paths = [path.join(root, "articles", "alfa.json"), path.join(root, "articles", "beta.json")];
  const before = await Promise.all(paths.map((file) => readFile(file, "utf8")));

  let installed = 0;
  const failing = delegatedFs({
    rename: async (from, to) => {
      if (from.endsWith(".tmp")) {
        installed += 1;
        if (installed === 2) throw Object.assign(new Error("mid-write failure"), { code: "EIO" });
      }
      await NODE_FS.rename(from, to);
    },
  });
  const store = new ContentStore(root, failing);
  await assert.rejects(
    store.writeDocumentsAtomically([
      makeDocument({ ...first, title: "Zmieniony tytuł Alfa dla testu transakcji" }),
      makeDocument({ ...second, title: "Zmieniony tytuł Beta dla testu transakcji" }),
    ]),
    ContentStoreError,
  );
  const after = await Promise.all(paths.map((file) => readFile(file, "utf8")));
  assert.deepEqual(after, before);
  assert.deepEqual((await readdir(path.join(root, "articles"))).sort(), ["alfa.json", "beta.json"]);
});

